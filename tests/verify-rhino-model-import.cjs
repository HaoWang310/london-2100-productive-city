// Safety/regression checks for Rhino 8 model replacement, run with Node 20+.
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const importer=fs.readFileSync('latest-model-loader.js','utf8');
new vm.Script(importer,{filename:'latest-model-loader.js'});
const anchor="<script>'use strict';";
const ix=html.lastIndexOf(anchor);
assert(ix>=0,'App application script is missing');
const end=html.indexOf('</script>',ix);
assert(end>ix,'App script closing tag is missing');
new vm.Script(html.slice(ix+8,end),{filename:'app-main.js'});
assert(html.includes('src="./latest-model-loader.js?v='),'Rhino source loader not included');
assert(importer.includes('File3dm.fromByteArray'),'Must decode actual 3DM geometry');
assert(importer.includes('database("set",m)'),'Imported geometry not persisted');
assert(importer.includes('location.reload()'),'App does not load updated source after import');
assert(importer.includes('modelName:file.name'),'Missing source provenance');
assert(importer.includes('topologyVerified:false'),'Unverified topology not labelled');
assert(importer.includes('边界未校核'),'Missing boundary QA disclosure');
assert(importer.includes('names.structure>0&&unresolved.some'),'Incomplete structures must be rejected');
assert(html.includes('if(model.meta?.imported)'),'Imported source branch missing');
assert(html.includes('roadDesignConfig.enabled=false'),'Legacy crossing overlay not disabled');
assert(html.includes('vehicleConfig.enabled=false'),'Legacy vehicles not disabled');
assert(html.includes('waterConfig.enabled=false'),'Legacy water not disabled');
assert(html.includes('landscapeConfig.enabled=false'),'Legacy landscape not disabled');
assert(html.includes('model.meta?.imported?"Rhino 场地组件"'),'Updated report provenance missing');
assert(html.includes('window.latestModelBridge?.controls()'),'File import button not mounted');
assert(html.includes('lowModel=null'),'Old unit LOD not invalidated');
assert(html.includes('const embeddedModel')===false,'Unused duplicate model retained');
console.log('PASS: parser syntax, model source integration, legacy overlay suppression and honest analysis provenance');
